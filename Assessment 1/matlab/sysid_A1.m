%% sysid_A1.m -- MR2006B Assessment 1: LS identification with ARX models
% Longitudinal: mean duty [%]          -> mean wheel speed v [m/s]
% Lateral:      differential duty [%]  -> yaw rate r [rad/s] (encoders)
% Training on PRBS, cross-validation on step / chirp / DLC / SLC and repeat runs.
% Output: figures (PDF) and results.tex in the paper folder (..\).
% Base MATLAB only (no toolboxes). Also runs in GNU Octave.
% Team EuroMotion - Thomas Resch A01832776
clear; clc; close all;

%% Settings
Ts   = 0.02;                    % sampling time [s] (TIM6, 50 Hz)
kx   = pi*72.6/3584/1000;       % m per encoder count (wheel 72.6 mm, 3584 counts/rev)
bw   = 0.22325;                 % track width [m] (WHEEL_BASE_MM)
Tpre = 1.5;                     % warm-up before the excitation [s]
Top  = [1.0 1.5];               % window for the operating point [s]
here = fileparts(mfilename('fullpath')); if isempty(here), here = pwd; end
dataDir = fullfile(here, 'data');
outDir  = fileparts(here);      % paper folder (one level up)

na_set = 1:3; nb_set = 1:3; nk_set = 1:2;   % ARX orders to test
tolR2  = 0.005;                              % parsimony: smallest order within tol

D(1).name = 'lon'; D(1).train = {'lon_prbs_1'};
D(1).val  = {'lon_step_1','lon_chirp_1','lon_prbs_2','lon_step_2','lon_chirp_2'};
D(1).ylab = 'v [m/s]';  D(1).ulab = '\bar{u} [%]';
D(2).name = 'lat'; D(2).train = {'lat_prbs_1'};
D(2).val  = {'lat_dlc_1','lat_slc_1','lat_prbs_2','lat_dlc_2','lat_slc_2'};
D(2).ylab = 'r [rad/s]'; D(2).ulab = '\Delta u [%]';

label = struct('lon_prbs','PRBS','lon_step','Multi-step','lon_chirp','Chirp', ...
               'lat_prbs','PRBS','lat_dlc','DLC','lat_slc','SLC');

isOct = exist('OCTAVE_VERSION','builtin') ~= 0;
fid = fopen(fullfile(outDir,'results.tex'),'w');
fprintf(fid,'%% generated by sysid_A1.m on %s -- do not edit by hand\n', datestr(now));
fprintf(fid,'\\renewcommand{\\DataReady}{1}\n');

for d = 1:2
    P = upper(D(d).name(1)); P = [P D(d).name(2:end)];   % Lon / Lat
    %% load data
    tr = {}; va = {}; vaName = {};
    for i = 1:numel(D(d).train)
        f = fullfile(dataDir,[D(d).train{i} '.csv']);
        if exist(f,'file'), tr{end+1} = loadRun(f, d, Ts, kx, bw, Top, Tpre); end %#ok<SAGROW>
    end
    for i = 1:numel(D(d).val)
        f = fullfile(dataDir,[D(d).val{i} '.csv']);
        if exist(f,'file')
            va{end+1} = loadRun(f, d, Ts, kx, bw, Top, Tpre); %#ok<SAGROW>
            vaName{end+1} = D(d).val{i}; %#ok<SAGROW>
        end
    end
    if isempty(tr) || isempty(va)
        error('Missing data for %s: need %s.csv and at least one validation file in %s', ...
              D(d).name, D(d).train{1}, dataDir);
    end
    fprintf('\n=== %s: %d training run(s), %d validation run(s) ===\n', upper(D(d).name), numel(tr), numel(va));

    %% order sweep
    rows = [];
    for na = na_set, for nb = nb_set, for nk = nk_set
        [th, ~] = lsArx(tr, na, nb, nk);
        r2t = mean(cellfun(@(z) r2(z.y, simArx(th, na, nb, nk, z.u)), tr));
        r2v = mean(cellfun(@(z) r2(z.y, simArx(th, na, nb, nk, z.u)), va));
        rows = [rows; na nb nk r2t r2v]; %#ok<AGROW>
    end, end, end
    best = max(rows(:,5));
    ok   = find(rows(:,5) >= best - tolR2);
    [~, j] = min(sum(rows(ok,1:3),2) + 1e-3*(1-rows(ok,5)));  % fewest parameters
    sel = rows(ok(j),:); na = sel(1); nb = sel(2); nk = sel(3);
    fprintf('selected ARX(%d,%d,%d): mean validation R2 = %.4f\n', na, nb, nk, sel(5));

    %% final model
    [th, Pc, s2, Phi, Y] = lsArx(tr, na, nb, nk);
    sd = sqrt(diag(Pc));
    a = th(1:na)'; b = th(na+1:end)';
    r2pred = r2(Y, Phi*th);                                   % one-step ahead
    r2sim  = mean(cellfun(@(z) r2(z.y, simArx(th, na, nb, nk, z.u)), tr));
    r2val  = cellfun(@(z) r2(z.y, simArx(th, na, nb, nk, z.u)), va);
    nrmse  = cellfun(@(z) sqrt(mean((z.y - simArx(th,na,nb,nk,z.u)).^2)), va);
    Kdc    = sum(b)/(1 + sum(a));
    p      = roots([1 a]);
    tauDom = -Ts/log(max(abs(p)));
    disp('theta = '); disp(th'); disp('covariance P = '); disp(Pc);
    fprintf('R2 one-step %.4f, R2 sim (train) %.4f, DC gain %.5g, dominant tau %.1f ms\n', ...
            r2pred, r2sim, Kdc, 1e3*tauDom);
    for i = 1:numel(va), fprintf('  val %-12s R2 = %.4f\n', vaName{i}, r2val(i)); end

    %% residual whiteness (training, one-step residuals)
    e = Y - Phi*th; lagMax = 25; N = numel(e);
    Ree = xc(e, e, lagMax); Rue = xc(cell2mat(cellfun(@(z) z.u(max([na nb+nk-1])+1:end), tr(:), 'UniformOutput', false)), e, lagMax);
    conf = 2.58/sqrt(N);
    fracW = mean(abs(Ree(2:end)) < conf); fracI = mean(abs(Rue) < conf);

    %% figures
    z = tr{1}; ys = simArx(th, na, nb, nk, z.u);
    f1 = figure('Visible','off'); setSize(f1, 3.5, 2.6);
    subplot(3,1,1:2); plot(z.t, z.y, 'k', z.t, ys, 'r--', 'LineWidth', 1); grid on;
    ylabel(['\Delta' D(d).ylab]); legend('measured', sprintf('ARX, R^2=%.3f', r2(z.y, ys)), 'Location','best');
    title(sprintf('Training: %s', label.(z.tag)));
    subplot(3,1,3); stairs(z.t, z.u, 'b'); grid on; ylabel(D(d).ulab); xlabel('t [s]');
    savePdf(f1, fullfile(outDir, sprintf('fig_%s_train.pdf', D(d).name)), isOct);

    nv = min(numel(va), 2);
    f2 = figure('Visible','off'); setSize(f2, 3.5, 1.35*nv + 0.5);
    for i = 1:nv
        z = va{i}; ys = simArx(th, na, nb, nk, z.u);
        subplot(nv,1,i); plot(z.t, z.y, 'k', z.t, ys, 'r--', 'LineWidth', 1); grid on;
        ylabel(['\Delta' D(d).ylab]);
        title(sprintf('Validation: %s (run %s), R^2=%.3f', label.(z.tag), z.run, r2val(i)));
    end
    xlabel('t [s]');
    savePdf(f2, fullfile(outDir, sprintf('fig_%s_val.pdf', D(d).name)), isOct);

    f3 = figure('Visible','off'); setSize(f3, 3.4, 1.9);
    L = 0:lagMax;
    subplot(2,1,1); stem(L, Ree, 'filled', 'MarkerSize', 2); hold on;
    plot([0 lagMax], conf*[1 1], 'r--', [0 lagMax], -conf*[1 1], 'r--'); grid on; ylabel('R_{ee}');
    title(sprintf('%s residual tests (99%% bounds)', P));
    subplot(2,1,2); stem(-lagMax:lagMax, Rue, 'filled', 'MarkerSize', 2); hold on;
    plot([-lagMax lagMax], conf*[1 1], 'r--', [-lagMax lagMax], -conf*[1 1], 'r--'); grid on;
    ylabel('R_{ue}'); xlabel('lag');
    savePdf(f3, fullfile(outDir, sprintf('fig_%s_resid.pdf', D(d).name)), isOct);

    %% results.tex
    w = @(name, val) fprintf(fid, '\\renewcommand{\\%s%s}{%s}\n', P, name, val);
    w('Order', sprintf('ARX(%d,%d,%d)', na, nb, nk));
    w('Na', num2str(na)); w('Nb', num2str(nb)); w('Nk', num2str(nk));
    w('Ntrain', num2str(numel(Y))); w('Nval', num2str(numel(va)));
    w('Sigma', sprintf('%.3g', sqrt(s2)));
    w('Rpred', sprintf('%.4f', r2pred)); w('Rsim', sprintf('%.4f', r2sim));
    w('Rval', sprintf('%.4f', mean(r2val))); w('Rvalmin', sprintf('%.4f', min(r2val)));
    w('K', sprintf('%.4g', Kdc)); w('Tau', sprintf('%.0f', 1e3*tauDom));
    w('Poles', strjoin(arrayfun(@cplx, p', 'UniformOutput', false), ', '));
    w('White', sprintf('%.0f', 100*fracW)); w('Indep', sprintf('%.0f', 100*fracI));
    w('Model', tfTex(a, b, nk));
    % parameter table rows
    s = '';
    for i = 1:na, s = [s sprintf('$a_{%d}$ & %s & %s \\\\ ', i, sci(a(i)), sci(sd(i)))]; end %#ok<AGROW>
    for i = 1:nb, s = [s sprintf('$b_{%d}$ & %s & %s \\\\ ', i, sci(b(i)), sci(sd(na+i)))]; end %#ok<AGROW>
    w('ParamRows', s);
    w('Cov', ['\begin{bmatrix}' matTex(Pc) '\end{bmatrix}']);
    % validation rows
    s = sprintf('%s (run %s, training) & %.4f & -- \\\\ ', label.(tr{1}.tag), tr{1}.run, r2sim);
    for i = 1:numel(va)
        s = [s sprintf('%s (run %s) & %.4f & %.3g \\\\ ', label.(va{i}.tag), va{i}.run, r2val(i), nrmse(i))]; %#ok<AGROW>
    end
    w('ValRows', s);
    % order table: best 6 + selected
    [~, ix] = sort(rows(:,5), 'descend'); ix = ix(1:min(5,end));
    iSel = find(ismember(rows(:,1:3), sel(1:3), 'rows'));
    if ~ismember(iSel, ix), ix = [ix; iSel]; end
    s = '';
    for i = ix'
        mark = ''; if all(rows(i,1:3) == sel(1:3)), mark = '$\star$'; end
        s = [s sprintf('(%d,%d,%d)%s & %d & %.4f & %.4f \\\\ ', rows(i,1:3), mark, ...
             rows(i,1)+rows(i,2), rows(i,4), rows(i,5))]; %#ok<AGROW>
    end
    w('OrderRows', s);
end
fclose(fid);
fprintf('\nWrote results.tex and figures to %s\n', outDir);

%% ========================= local functions =============================
function z = loadRun(f, d, Ts, kx, bw, Top, Tpre)
    txt = fileread(f);
    tok = regexp(txt, '(?m)^\s*(\d+),(-?\d+),(-?\d+),(-?\d+),(-?\d+)\s*$', 'tokens');
    M = cellfun(@str2double, vertcat(tok{:}));
    uL = M(:,2)/100; uR = M(:,3)/100;
    vL = M(:,4)*kx/Ts; vR = M(:,5)*kx/Ts;          % raw speed [m/s], no filter
    t  = M(:,1)*Ts;
    if d == 1, u = (uL + uR)/2; y = (vL + vR)/2;     % longitudinal
    else,      u = (uR - uL)/2; y = (vR - vL)/bw;    % lateral (yaw rate)
    end
    op = t >= Top(1) & t < Top(2);
    keep = t >= Top(1);
    z.u = u(keep) - mean(u(op)); z.y = y(keep) - mean(y(op));
    z.t = t(keep) - Tpre; z.u0 = mean(u(op)); z.y0 = mean(y(op));
    [~, nm] = fileparts(f); k = find(nm == '_', 1, 'last');
    z.tag = nm(1:k-1); z.run = nm(k+1:end);
end

function [th, P, s2, Phi, Y] = lsArx(runs, na, nb, nk)
    Phi = []; Y = [];
    for i = 1:numel(runs)
        u = runs{i}.u; y = runs{i}.y; n0 = max(na, nb+nk-1) + 1; N = numel(y);
        R = zeros(N-n0+1, na+nb);
        for j = 1:na, R(:,j)    = -y(n0-j:N-j); end
        for j = 1:nb, R(:,na+j) =  u(n0-nk-j+1:N-nk-j+1); end
        Phi = [Phi; R]; Y = [Y; y(n0:N)]; %#ok<AGROW>
    end
    th = (Phi'*Phi) \ (Phi'*Y);                 % least squares
    e  = Y - Phi*th;
    s2 = (e'*e)/(numel(Y) - numel(th));         % noise variance
    P  = s2 * inv(Phi'*Phi);                    % covariance of theta
end

function ys = simArx(th, na, nb, nk, u)
    a = th(1:na)'; b = th(na+1:na+nb)';
    ys = filter([zeros(1,nk) b], [1 a], u);     % free-run simulation
end

function v = r2(y, yh)
    v = 1 - sum((y - yh).^2)/sum((y - mean(y)).^2);
end

function R = xc(x, y, L)                        % normalised cross-correlation
    x = x - mean(x); y = y - mean(y); N = numel(x);
    if isequal(x, y), lags = 0:L; else, lags = -L:L; end
    R = zeros(size(lags));
    for i = 1:numel(lags)
        k = lags(i);
        if k >= 0, R(i) = sum(x(1:N-k).*y(1+k:N)); else, R(i) = sum(x(1-k:N).*y(1:N+k)); end
    end
    R = R / sqrt(sum(x.^2)*sum(y.^2));
end

function s = sci(v)
    if v == 0, s = '0'; return; end
    e = floor(log10(abs(v)));
    if e >= -2 && e <= 3, s = sprintf('%.4f', v);
    else, s = sprintf('$%.3f\\times10^{%d}$', v/10^e, e); end
end

function s = cplx(p)
    if abs(imag(p)) < 1e-9, s = sprintf('%.4f', real(p));
    else, s = sprintf('%.4f%s%.4fj', real(p), char(43 - 2*(imag(p)<0)), abs(imag(p))); end
end

function s = matTex(M)
    s = '';
    for i = 1:size(M,1)
        r = arrayfun(@(v) sprintf('%.2e', v), M(i,:), 'UniformOutput', false);
        s = [s strjoin(r, ' & ')]; %#ok<AGROW>
        if i < size(M,1), s = [s ' \\ ']; end %#ok<AGROW>
    end
    s = regexprep(s, '(-?\d\.\d\d)e([+-])0?(\d+)', '$1{\\cdot}10^{$2$3}');
    s = strrep(s, '^{+', '^{');
end

function s = tfTex(a, b, nk)
    num = ''; for i = 1:numel(b), num = [num term(b(i), nk+i-1, isempty(num))]; end %#ok<AGROW>
    den = '1'; for i = 1:numel(a), den = [den term(a(i), i, false)]; end %#ok<AGROW>
    s = sprintf('\\frac{%s}{%s}', num, den);
end

function s = term(c, k, first)
    if first, sg = ''; if c < 0, sg = '-'; end
    else, sg = '+'; if c < 0, sg = '-'; end
    end
    if k == 0, zs = ''; else, zs = sprintf('z^{-%d}', k); end
    s = sprintf('%s%.4g%s', sg, abs(c), zs);
end

function setSize(f, wIn, hIn)
    set(f, 'Units','inches', 'Position',[1 1 wIn hIn], 'PaperUnits','inches', ...
        'PaperSize',[wIn hIn], 'PaperPosition',[0 0 wIn hIn]);
    set(findall(f,'-property','FontSize'), 'FontSize', 7);
end

function savePdf(f, name, isOct)
    set(findall(f,'-property','FontSize'), 'FontSize', 7);
    if ~isOct && exist('exportgraphics','file')
        exportgraphics(f, name, 'ContentType','vector');
    else
        print(f, name, '-dpdf');
    end
    close(f);
end
