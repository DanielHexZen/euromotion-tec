function [R, out] = design_noise_models(make_plots, T_rec_h)
%DESIGN_NOISE_MODELS  Q and R of the EKF derived from the sensor models.
%
%   [R, out] = design_noise_models(make_plots, T_rec_h)
%   Prints how every ekf_* noise parameter maps to a physical quantity and how
%   to obtain it from a measurement, evaluates the consequences of the
%   current (unmeasured!) defaults, and demonstrates allan_gyro on a
%   SIMULATED stationary record of T_rec_h hours (default 2 h) generated
%   with the default nd and q_bg: the helper must return them.
%   No real IMU log exists yet; see README "Loading real data".
if nargin < 1, make_plots = false; end
if nargin < 2, T_rec_h = 2; end
p = ekf_params();
R = [];
fprintf('\n=== Q/R mapping (all defaults are placeholders until measured) ===\n');
fprintf(['ekf_gyro_nd  = angle random walk N of the projected yaw rate [rad/s/sqrt(Hz)]\n' ...
         '               source: Allan deviation at tau = 1 s (slope -1/2), or datasheet noise\n' ...
         '               density [mdps/sqrt(Hz)] * pi/180e3.  Q_tt += nd^2*dt while moving.\n']);
fprintf('               default %.1e -> heading sigma after 100 s of driving: %.3f deg\n', ...
    p.ekf_gyro_nd, sqrt(p.ekf_gyro_nd^2*100)*180/pi);
fprintf(['ekf_q_bg     = rate random walk K^2 [(rad/s)^2/s]; Allan slope +1/2: sigma(tau) = K sqrt(tau/3)\n' ...
         '               default %.1e -> bias sigma growth over a 60 s leg: %.4f deg/s\n'], ...
    p.ekf_q_bg, sqrt(p.ekf_q_bg*60)*180/pi);
fprintf(['ZUPT R       = nd^2/T + ekf_zupt_floor^2: variance of the mean of white rate noise over T\n' ...
         '               T = %.1f s -> sigma %.2e rad/s (%.4f deg/s); one waypoint hold (10.5 s) of\n' ...
         '               ten ZUPTs -> %.2e rad/s, floor-limited at %.1e\n'], p.ekf_zupt_T, ...
    sqrt(p.ekf_gyro_nd^2/p.ekf_zupt_T + p.ekf_zupt_floor^2), ...
    sqrt(p.ekf_gyro_nd^2/p.ekf_zupt_T + p.ekf_zupt_floor^2)*180/pi, ...
    sqrt((p.ekf_gyro_nd^2/p.ekf_zupt_T + p.ekf_zupt_floor^2)/10), p.ekf_zupt_floor);
fprintf(['             note: the floor is applied per ZUPT, so ten ZUPTs reduce it by sqrt(10); if the\n' ...
         '               floor stands for a correlated error (temperature, quantisation), that\n' ...
         '               reduction is optimistic.\n']);
fprintf(['ekf_gyro_sf  = gyro scale-factor uncertainty after imu_gz_scale. From the 10-turn spin of H7:\n' ...
         '               residual delta (rad) after 20*pi rad -> sf = delta/(20 pi). H7 pass (0.5 deg):\n' ...
         '               sf <= %.1e. Default %.3g is the UNCALIBRATED value.\n'], 0.5*pi/180/(20*pi), p.ekf_gyro_sf);
fprintf(['               Q model (finding F-3): spec Q_tt += (sf*dth)^2 per step treats a constant\n' ...
         '               scale error as white. For one 90 deg turn it gives variance sf^2*(pi/2)^2/n_steps\n' ...
         '               (n_steps = 120 at 50 Hz, 480 at 200 Hz) instead of (sf*pi/2)^2:\n']);
for hz = [50 200]
    nst = (pi/2)/p.nav_turn_w*hz;
    fprintf('                 %3d Hz: spec sigma %.4f deg, true %.3f deg, per-radian (corr 2 pi) %.3f deg\n', ...
        hz, sqrt(p.ekf_gyro_sf^2*(pi/2)^2/nst)*180/pi, p.ekf_gyro_sf*pi/2*180/pi, ...
        sqrt(p.ekf_gyro_sf^2*2*pi*pi/2)*180/pi);
end
fprintf(['ekf_kd       = random distance noise [m]: variance per metre. From repeated D5000 (n runs):\n' ...
         '               kd = var(end error)/5 m AFTER removing the mean (the mean is the scale s).\n' ...
         '               default %.1e -> sigma %.1f mm over 5 m, %.1f mm over 40 m\n'], p.ekf_kd, ...
    1e3*sqrt(p.ekf_kd*5), 1e3*sqrt(p.ekf_kd*40));
fprintf(['ekf_q_s      = drift of the odometry scale [1/s] (surface, load, tyre). Expected change ds over\n' ...
         '               a run of T s: q_s = ds^2/T. default %.1e -> sigma %.2f %% over 900 s\n'], ...
    p.ekf_q_s, 100*sqrt(p.ekf_q_s*900));
fprintf(['ekf_sig_edge = sigma of the footprint position at the event: sqrt(spot^2 + ragged^2 +\n' ...
         '               (v_lateral*timestamp error)^2). Spot: ROI 4x4 at h0 = %.2f m -> %.1f mm\n' ...
         '               diameter; timestamp error +-poll/2 = 2.5 ms (negligible laterally).\n'], ...
    p.gnd_h0, 1e3*2*p.gnd_h0*tan(7.5*pi/180));
fprintf('ekf_slip_thr = %.2f rad/s vs. encoder yaw-rate resolution 1 count: %.4f rad/s at 50 Hz, %.4f at 200 Hz\n', ...
    p.ekf_slip_thr, p.odo_m_per_cnt/(p.odo_wheelbase*0.02), p.odo_m_per_cnt/(p.odo_wheelbase*0.005));
fprintf(['               and vs. systematic residuals: wheel mismatch 0.64 %% at 0.45 m/s -> %.3f rad/s,\n' ...
         '               wheelbase error 2 %% at 1.5 rad/s -> %.3f rad/s. Margin x%.1f.\n'], ...
    0.0064*0.45/p.odo_wheelbase, 0.02*1.5, p.ekf_slip_thr/max(0.0064*0.45/p.odo_wheelbase, 0.03));

% ------------------------------------------------ Allan variance demonstration
fs = 100;                               % decimated rate (equivalent white density)
n  = round(T_rec_h*3600*fs);
nd = p.ekf_gyro_nd;  qb = p.ekf_q_bg;
% demo data only (not part of the reference path): fixed-seed randn
if exist('OCTAVE_VERSION', 'builtin'), randn('seed', 2024); else, rng(2024, 'twister'); end %#ok<RAND>
bw = cumsum(sqrt(qb/fs)*randn(n, 1));
w  = 0.3*pi/180 + bw + nd*sqrt(fs)*randn(n, 1);
A  = allan_gyro(w, fs);
out.A = A;
fprintf('\nAllan demo (simulated %.1f h at %d Hz): nd true %.3e fit %.3e (%.1f %%), q_bg true %.2e fit %.2e (%.0f %%)\n', ...
    T_rec_h, fs, nd, A.ekf_gyro_nd, 100*(A.ekf_gyro_nd/nd - 1), qb, A.ekf_q_bg, 100*(A.ekf_q_bg/qb - 1));
R = [R, vres('Allan helper recovers ekf_gyro_nd (sim data)', double(abs(A.ekf_gyro_nd/nd - 1) < 0.05), ...
    sprintf('%.2e vs %.2e', A.ekf_gyro_nd, nd), '+-5 %')];
R = [R, vres('Allan helper recovers ekf_q_bg (sim data)', double(abs(A.ekf_q_bg/qb - 1) < 0.5), ...
    sprintf('%.2e vs %.2e', A.ekf_q_bg, qb), '+-50 % (few long clusters)')];
if make_plots && can_plot()
    f = figure('Visible', 'off');
    loglog(A.tau, A.adev*180/pi*3600, 'b.-', A.tau, sqrt(A.N^2./A.tau + A.K^2*A.tau/3)*180/pi*3600, 'r--');
    grid on; xlabel('\tau [s]'); ylabel('Allan deviation [deg/h]');
    legend('simulated record', 'fit N^2/\tau + K^2\tau/3');
    title('Allan deviation (simulated stationary gyro)');
    save_fig(f, 'allan_demo');
end
end
