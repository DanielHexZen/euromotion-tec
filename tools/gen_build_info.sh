#!/bin/sh
# Pre-build step (spec §4.7): writes Core/Inc/build_info.h with the git short hash, a dirty flag
# and the build date. CubeIDE: Properties > C/C++ Build > Settings > Build Steps > Pre-build
# command  ../../tools/gen_build_info.sh   (the script finds the repository from its own path).
set -e
root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/Challenge_TestHC/Core/Inc/build_info.h"
hash="$(git -C "$root" rev-parse --short HEAD 2>/dev/null || echo nogit)"
git -C "$root" diff --quiet HEAD 2>/dev/null || hash="$hash-dirty"
tmp="$(mktemp)"
printf '/* generated by tools/gen_build_info.sh - do not edit */\n#define BUILD_GIT  "%s"\n#define BUILD_DATE "%s"\n' \
    "$hash" "$(date +%Y-%m-%d)" > "$tmp"
cmp -s "$tmp" "$out" 2>/dev/null && rm "$tmp" || mv "$tmp" "$out"
